  function translate(source) {
    // Retain whitespace and avoid changing filenames, identifiers and live peer names.
    const match = /^(\s*)([\s\S]*?)(\s*)$/.exec(source);
    if (!match || !match[2]) return source;
    const key = match[2];
    let value = Object.prototype.hasOwnProperty.call(JA, key) ? JA[key] : null;
    if (value === null) {
      for (const [pattern, format] of matchers) {
        const found = key.match(pattern);
        if (found) { value = format(...found.slice(1)); break; }
      }
    }
    // Handle accessibility suffix before splitting feature/state/reason segments.
    if (value === null && key.endsWith(' (opens its page)')) {
      const part = key.slice(0, -' (opens its page)'.length);
      const localized = translate(part);
      if (localized !== part) value = localized + ' （設定ページを開きます）';
    }
    // Device names prefix a state with an em dash, e.g. "rion-pc — Connected".
    if (value === null && key.includes(' — ')) {
      const i = key.lastIndexOf(' — ');
      const right = key.slice(i + 3);
      const translated = translate(right);
      if (translated !== right) value = key.slice(0, i + 3) + translated;
    }
    // Tile tooltips append a reachability explanation to the state.
    if (value === null && key.includes(': ')) {
      const i = key.indexOf(': ');
      const left = key.slice(0, i), right = key.slice(i + 2);
      const translatedLeft = translate(left), translatedRight = translate(right);
      if (translatedLeft !== left || translatedRight !== right)
        value = translatedLeft + '：' + translatedRight;
    }
    // Aurora hover hints combine feature, on/off and reason using a bullet separator.
    if (value === null && key.includes(' · ')) {
      const parts = key.split(' · ');
      const localized = parts.map((part) => translate(part));
      if (localized.some((part, i) => part !== parts[i])) value = localized.join(' · ');
    }
    return value === null ? source : match[1] + value + match[3];
  }
